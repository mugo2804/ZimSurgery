export const ICD10: Icd10[] = RAW.map(([code, description]) => ({ code, description }));

export function searchIcd10(q: string, limit = 20): Icd10[] {
  const s = q.trim().toLowerCase();
  if (!s) return [];
  const words = s.split(/\s+/);
  return ICD10.filter((d) => d.code.toLowerCase().startsWith(s) || words.every((w) => d.description.toLowerCase().includes(w))).slice(0, limit);
}
